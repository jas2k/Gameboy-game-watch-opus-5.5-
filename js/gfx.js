  /* ---------- sprites ---------- */
  // rows: array of equal-length strings; pal: { char: color }. '.' / ' ' = transparent
  GW.spr = function (rows, pal) {
    const h = rows.length, w = rows[0].length;
    const c = document.createElement('canvas');
    c.width = w; c.height = h;
    const g = c.getContext('2d');
    for (let y = 0; y < h; y++) {
      const row = rows[y];
      for (let x = 0; x < w; x++) {
        const ch = row[x];
        if (ch === '.' || ch === ' ' || ch === undefined) continue;
        const col = pal[ch];
        if (!col) continue;
        g.fillStyle = col;
        g.fillRect(x, y, 1, 1);
      }
    }
    return { img: c, w, h, fx: null, fy: null, fxy: null };
  };

  GW.canvasSpr = function (w, h, paint) {
    const c = document.createElement('canvas');
    c.width = w; c.height = h;
    const g = c.getContext('2d');
    g.imageSmoothingEnabled = false;
    paint(g, w, h);
    return { img: c, w, h, fx: null, fy: null, fxy: null };
  };

  function flipped(s, fx, fy) {
    const c = document.createElement('canvas');
    c.width = s.w; c.height = s.h;
    const g = c.getContext('2d');
    g.translate(fx ? s.w : 0, fy ? s.h : 0);
    g.scale(fx ? -1 : 1, fy ? -1 : 1);
    g.drawImage(s.img, 0, 0);
    return c;
  }

  GW.draw = function (ctx, s, x, y, flipX, flipY) {
    if (!s) return;
    let img = s.img;
    if (flipX && flipY) img = s.fxy || (s.fxy = flipped(s, true, true));
    else if (flipX) img = s.fx || (s.fx = flipped(s, true, false));
    else if (flipY) img = s.fy || (s.fy = flipped(s, false, true));
    ctx.drawImage(img, Math.round(x), Math.round(y));
  };

  // silhouette of a sprite in a single color (cached per color)
  GW.tint = function (s, color) {
    s._tints = s._tints || {};
    if (s._tints[color]) return s._tints[color];
    const t = GW.canvasSpr(s.w, s.h, (g) => {
      g.drawImage(s.img, 0, 0);
      g.globalCompositeOperation = 'source-in';
      g.fillStyle = color;
      g.fillRect(0, 0, s.w, s.h);
    });
    s._tints[color] = t;
    return t;
  };

  // pixel-art blob from a boolean mask function, with 1px outline
  GW.blob = function (w, h, inside, fill, outline, shade) {
    return GW.canvasSpr(w, h, (g) => {
      const m = [];
      for (let y = 0; y < h; y++) {
        m[y] = [];
        for (let x = 0; x < w; x++) m[y][x] = inside(x + 0.5, y + 0.5);
      }
      const at = (x, y) => (x >= 0 && y >= 0 && x < w && y < h ? m[y][x] : false);
      for (let y = 0; y < h; y++) {
        for (let x = 0; x < w; x++) {
          if (!m[y][x]) continue;
          const edge = !at(x - 1, y) || !at(x + 1, y) || !at(x, y - 1) || !at(x, y + 1);
          let col = fill;
          if (edge && outline) col = outline;
          else if (shade) col = shade(x, y, fill) || fill;
          g.fillStyle = col;
          g.fillRect(x, y, 1, 1);
        }
      }
    });
  };

